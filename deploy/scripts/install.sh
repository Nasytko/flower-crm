#!/usr/bin/env bash
# erpbuket1 first-time HostFly installer (idempotent).
#
# Usage (from /opt/erpbuket1 after git clone):
#   ./deploy/scripts/install.sh
#
# Optional:
#   ALLOW_NONSTANDARD_APP_DIR=1
#   ERP_ENV_FILE=/etc/erpbuket1/production.env
#   NONINTERACTIVE=1
#   SKIP_COMPOSE_UP=1
#   CONFIRM_CREATE_EMPTY_DB=YES       # ONLY interrupted_first_install (env, no volume, no host evidence)
#   CONFIRM_VOLUME_IS_ERP_DATA=YES    # ONLY volume_unproven after manual docker volume inspect
#   lost_volume (marker/containers, volume gone) is ALWAYS blocked — dumps/nginx alone are NOT lost_volume.
#
# Does NOT: touch Nginx/Certbot, bootstrap users, seed DB, down -v, touch shopbuket1.

set -Eeuo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/erpbuket1-env.sh
source "${SCRIPT_DIR}/lib/erpbuket1-env.sh"

umask 077

log() { erpbuket1_log "install: $*"; }
die() { erpbuket1_die "install: $*"; }

prompt() {
  local msg="$1"
  local def="${2:-}"
  local reply
  if [[ "${NONINTERACTIVE:-0}" == "1" ]]; then
    printf '%s' "${def}"
    return 0
  fi
  if [[ -n "${def}" ]]; then
    read -r -p "${msg} [${def}]: " reply || true
    printf '%s' "${reply:-${def}}"
  else
    read -r -p "${msg}: " reply || true
    printf '%s' "${reply}"
  fi
}

confirm_yes() {
  local msg="$1"
  local reply
  if [[ "${NONINTERACTIVE:-0}" == "1" ]]; then
    return 0
  fi
  read -r -p "${msg} [y/N]: " reply || true
  [[ "${reply}" == "y" || "${reply}" == "Y" || "${reply}" == "yes" ]]
}

gen_url_safe_secret() {
  local n="${1:-32}"
  openssl rand -base64 48 | tr -d '/+=' | head -c "${n}"
}

write_production_env() {
  local domain="$1" web_port="$2" api_port="$3" tz="$4"
  local pg_user="$5" pg_db="$6" pg_pass="$7" jwt="$8"
  local tmp

  tmp="${ERP_TMP_DIR}/production.env.new"
  cat >"${tmp}" <<EOF
# Generated by deploy/scripts/install.sh -- keep chmod 600
# Path: ${ERP_ENV_FILE}

ERP_DOMAIN=${domain}
WEB_URL=https://${domain}
NEXT_PUBLIC_API_URL=https://${domain}

ERP_WEB_PORT=${web_port}
ERP_API_PORT=${api_port}

NODE_ENV=production
TRUST_PROXY=1
BUSINESS_TIME_ZONE=${tz}

POSTGRES_USER=${pg_user}
POSTGRES_DB=${pg_db}
POSTGRES_PASSWORD=${pg_pass}
DATABASE_URL=postgresql://${pg_user}:${pg_pass}@postgres:5432/${pg_db}?schema=public

JWT_ACCESS_SECRET=${jwt}
JWT_ACCESS_TTL_SECONDS=900
SESSION_TTL_SECONDS=1209600
AUTH_COOKIE_NAME=erp_refresh
AUTH_LOGIN_MAX_ATTEMPTS=20
AUTH_LOGIN_WINDOW_SECONDS=60
EOF

  mkdir -p "$(dirname "${ERP_ENV_FILE}")"
  install -m 600 "${tmp}" "${ERP_ENV_FILE}"
  log "wrote ${ERP_ENV_FILE} (secrets not printed)"
}

prepare_env_interactive() {
  if [[ -f "${ERP_ENV_FILE}" ]]; then
    log "existing ${ERP_ENV_FILE} preserved (no secret regeneration)"
    return 0
  fi

  if [[ "${NONINTERACTIVE:-0}" == "1" ]]; then
    die "missing ${ERP_ENV_FILE}; create from deploy/env/production.env.example before NONINTERACTIVE install"
  fi

  log "creating new production.env (first install)"
  local domain web_port api_port tz pg_user pg_db pg_pass jwt
  domain="$(prompt "ERP public domain (DNS A/AAAA to this VPS)" "")"
  [[ -n "${domain}" ]] || die "ERP_DOMAIN is required"
  erpbuket1_validate_hostname "${domain}" || die "ERP_DOMAIN must be a DNS hostname (letters/digits/hyphen/dot only)"
  web_port="$(prompt "ERP_WEB_PORT (loopback)" "3100")"
  api_port="$(prompt "ERP_API_PORT (loopback)" "3101")"
  tz="$(prompt "BUSINESS_TIME_ZONE" "Europe/Minsk")"
  pg_user="$(prompt "POSTGRES_USER" "erpbuket1")"
  pg_db="$(prompt "POSTGRES_DB" "flower_crm")"

  if ! [[ "${web_port}" =~ ^[0-9]+$ && "${api_port}" =~ ^[0-9]+$ ]]; then
    die "ports must be numeric"
  fi
  if [[ "${web_port}" == "${api_port}" ]]; then
    die "WEB and API ports must differ"
  fi
  if ! [[ "${pg_user}" =~ ^[A-Za-z0-9_]+$ && "${pg_db}" =~ ^[A-Za-z0-9_]+$ ]]; then
    die "POSTGRES_USER/DB must be alphanumeric/underscore"
  fi

  log "generating URL-safe POSTGRES_PASSWORD and JWT_ACCESS_SECRET"
  pg_pass="$(gen_url_safe_secret 32)"
  jwt="$(gen_url_safe_secret 64)"

  echo
  log "About to write ${ERP_ENV_FILE} with domain=${domain} ports=${web_port}/${api_port}"
  confirm_yes "Proceed?" || die "aborted by operator"

  write_production_env "${domain}" "${web_port}" "${api_port}" "${tz}" "${pg_user}" "${pg_db}" "${pg_pass}" "${jwt}"
}

ensure_dirs() {
  mkdir -p "${ERP_BACKUP_DIR_DEFAULT}"
  chmod 700 "${ERP_BACKUP_DIR_DEFAULT}" || true
  mkdir -p "$(dirname "${ERP_ENV_FILE}")"
  chmod 755 "$(dirname "${ERP_ENV_FILE}")" || true
  mkdir -p "${ERP_STATE_DIR_DEFAULT}"
  chmod 755 "${ERP_STATE_DIR_DEFAULT}" || true
  if [[ -f "${ERP_ENV_FILE}" ]]; then
    chmod 600 "${ERP_ENV_FILE}" || true
  fi
  log "dirs ready"
}

check_os_hint() {
  if [[ -r /etc/os-release ]]; then
    # shellcheck disable=SC1091
    . /etc/os-release
    log "OS: ${PRETTY_NAME:-unknown}"
    if [[ "${ID:-}" != "ubuntu" ]]; then
      erpbuket1_warn "install targeted at Ubuntu 24.04; detected ID=${ID:-unknown}"
    fi
  else
    erpbuket1_warn "cannot read /etc/os-release"
  fi
}

run_first_stack_bringup() {
  if [[ "${SKIP_COMPOSE_UP:-0}" == "1" ]]; then
    log "SKIP_COMPOSE_UP=1 -- env/dirs prepared only"
    log "Next: ./deploy/scripts/deploy.sh"
    log "Nginx: ./deploy/scripts/install-nginx.sh (explicit)"
    exit 0
  fi

  log "building images"
  erpbuket1_compose build || die "build failed"

  log "starting postgres (new volume created if absent)"
  erpbuket1_ensure_postgres_ready 60 2

  log "prisma migrate deploy"
  erpbuket1_compose run --rm migrate || die "migrate failed -- API/Web not started"

  log "starting api + web"
  erpbuket1_compose up -d api web || die "failed to start api/web"

  log "internal healthcheck"
  "${SCRIPT_DIR}/healthcheck.sh" --mode=internal || die "healthcheck failed after install"

  erpbuket1_write_install_marker

  log "SUCCESS -- install complete"
  log "Git: $(git rev-parse --short HEAD 2>/dev/null || echo n/a)"
  log "Loopback web: http://127.0.0.1:$(erpbuket1_env_get ERP_WEB_PORT)/login"
  log "Loopback api:  http://127.0.0.1:$(erpbuket1_env_get ERP_API_PORT)/api/v1/health"
  log "Nginx/HTTPS: install-nginx.sh then issue-cert.sh (separate confirmed steps)"
  log "Create first DIRECTOR: bootstrap-initial-users.sh (manual)"
}

main() {
  erpbuket1_setup_tmp_trap
  erpbuket1_acquire_lock
  erpbuket1_require_app_dir

  local root state
  root="$(erpbuket1_root_dir)"
  cd "${root}"
  log "app root: ${root}"

  check_os_hint
  erpbuket1_check_commands git curl openssl
  if ! erpbuket1_need_cmd docker; then
    die "Docker Engine not found. Install Docker manually, then re-run."
  fi
  erpbuket1_check_docker
  erpbuket1_check_resources
  erpbuket1_check_shop_coexistence
  ensure_dirs

  state="$(erpbuket1_detect_db_state)"
  log "pre-install state=${state}"

  case "${state}" in
    existing)
      log "ERP already installed (env + proven volume). Handing off to deploy.sh"
      erpbuket1_validate_env
      erpbuket1_check_ports_available
      if [[ "${SKIP_COMPOSE_UP:-0}" == "1" ]]; then
        log "SKIP_COMPOSE_UP=1 on existing install -- done"
        exit 0
      fi
      exec "${SCRIPT_DIR}/deploy.sh"
      ;;
    volume_unproven)
      erpbuket1_validate_env
      if [[ "${CONFIRM_VOLUME_IS_ERP_DATA:-}" != "YES" ]]; then
        erpbuket1_die_volume_unproven
      fi
      erpbuket1_warn "CONFIRM_VOLUME_IS_ERP_DATA=YES -- proceeding via deploy.sh"
      erpbuket1_check_ports_available
      exec "${SCRIPT_DIR}/deploy.sh"
      ;;
    ambiguous_volume_without_env)
      die "volume ${ERP_VOLUME_NAME} exists but production.env is missing. Restore env manually; refusing new secrets against existing data."
      ;;
    lost_volume)
      erpbuket1_die_lost_volume
      ;;
    interrupted_first_install)
      if [[ "${CONFIRM_CREATE_EMPTY_DB:-}" != "YES" ]]; then
        die "interrupted first install: ${ERP_ENV_FILE} exists, volume missing, no host install evidence (marker/containers). Set CONFIRM_CREATE_EMPTY_DB=YES to finish, or restore volume. Dump files alone do not block this. lost_volume cannot use this flag."
      fi
      erpbuket1_warn "CONFIRM_CREATE_EMPTY_DB=YES -- finishing interrupted first install with NEW empty volume"
      erpbuket1_validate_env
      erpbuket1_check_ports_available
      erpbuket1_check_dns_warn
      run_first_stack_bringup
      ;;
    fresh)
      prepare_env_interactive
      erpbuket1_validate_env
      erpbuket1_check_ports_available
      erpbuket1_check_dns_warn
      run_first_stack_bringup
      ;;
    *)
      die "unknown state: ${state}"
      ;;
  esac
}

main "$@"
